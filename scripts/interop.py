"""Independent bidirectional oracle: numpy 2.2.6 / pynrrd 1.1.3. No runtime dependency."""
import argparse, io, pathlib, subprocess, tempfile, json, os
import numpy as np
import nrrd
ROOT = pathlib.Path(__file__).resolve().parents[1]
TYPES = [('I8','i1',[-128,-1,0,127]),('U8','u1',[0,1,128,255]),('I16','i2',[-32768,-1,0,32767]),('U16','u2',[0,1,32768,65535]),('I32','i4',[-2147483648,-1,0,2147483647]),('U32','u4',[0,1,2147483648,4294967295]),('F32','f4',[-12.5,-0.125,0.5,1024.25]),('F64','f8',[-1.0e100,-0.125,0.5,1.0e100])]
def vectors():
    for scalar,dtype,values in TYPES:
        for encoding in ('raw','ascii','hex'):
            for endian in ('little','big'):
                for detached in (False,True):
                    yield scalar,dtype,values,encoding,endian,detached

def literal(data):
    return 'b"'+''.join('\\x%02x'%v for v in data)+'"'

def fixtures():
    blocks=['// Generated by scripts/interop.py from pynrrd, not production code.']
    with tempfile.TemporaryDirectory() as folder:
        p=pathlib.Path(folder)
        for i,(scalar,dtype,values,encoding,endian,detached) in enumerate(vectors()):
            arr=np.array(values,dtype=np.dtype(dtype).newbyteorder('<' if endian=='little' else '>')).reshape((2,2),order='F')
            header={'encoding':'raw' if encoding=='hex' else encoding,'labels':['x','time'],'kinds':['domain','time'],'content':'oracle fixture','source':'pynrrd'}
            path=p/('test.nhdr' if detached else 'test.nrrd')
            nrrd.write(str(path),arr,header,index_order='F')
            data=path.read_bytes()
            # Writer timestamps are irrelevant to format behavior and nondeterministic.
            head,body=data.split(b'\n\n',1)
            head=b'\n'.join(line for line in head.splitlines() if not line.startswith(b'#'))+b'\n\n'
            if detached:
                # The writer's basename may differ per encoding.
                fields=nrrd.read_header(str(path))
                body=(p/fields['data file']).read_bytes()
                expression='@nrrd.read_nrrd('+literal(head)+', detached='+literal(body)+')'
            else:
                expression='@nrrd.read_nrrd('+literal(head+body)+')'
            if encoding=='hex':
                if detached: body=body.hex().encode('ascii')
                else:
                    h,b=(head+body).split(b'\n\n',1); head=h+b'\n\n'; body=b.hex().encode('ascii')
                head=head.replace(b'encoding: raw',b'encoding: hex')
                expression='@nrrd.read_nrrd('+literal(head)+((', detached='+literal(body)) if detached else '')+')' if detached else '@nrrd.read_nrrd('+literal(head+body)+')'
            expected='['+', '.join(repr(float(x)).replace('1e+', '1.0e+') for x in values)+']'
            blocks.append('test "pynrrd vector %02d %s %s %s %s" {\n  let t = %s\n  assert_eq(t.values(), %s)\n  assert_eq(t.shape().sizes(), [2, 2])\n  assert_eq(t.scalar(), @nrrd.%s)\n  assert_eq(t.metadata().labels, ["x", "time"])\n  assert_eq(t.metadata().custom["source"], "pynrrd")\n}'%(i,scalar,encoding,endian,'detached' if detached else 'attached',expression,expected,scalar))
    return '\n\n'.join(blocks)+'\n'

def main():
    parser=argparse.ArgumentParser(); parser.add_argument('--generate',action='store_true'); parser.add_argument('--check',action='store_true'); args=parser.parse_args()
    generated=fixtures()
    path=ROOT/'oracle_test.mbt'
    # moon fmt formats the generated source; compare formatted temporary candidate.
    if args.generate:
        path.write_text(generated,encoding='utf8')
        return
    # Regenerate through formatter in a temporary module, preserving the real checkout.
    with tempfile.TemporaryDirectory() as folder:
        temp=pathlib.Path(folder); (temp/'moon.mod').write_text('name = "oracle/fixture"\n',encoding='utf8'); (temp/'moon.pkg').write_text('import { "3smallpig/moonnrrd" @nrrd }\n',encoding='utf8'); (temp/'oracle_test.mbt').write_text(generated,encoding='utf8')
        subprocess.run(['moon','fmt'],cwd=temp,check=True,stdout=subprocess.PIPE)
        assert path.read_bytes()==(temp/'oracle_test.mbt').read_bytes(), 'oracle fixtures differ: regenerate and format'
    subprocess.run(['moon','test','--target','js','--filter','pynrrd vector*'],cwd=ROOT,check=True)
    result=subprocess.run(['moon','run','cmd/interop','--target','js'],cwd=ROOT,check=True,text=True,stdout=subprocess.PIPE)
    lines=result.stdout.strip().splitlines()
    assert len(lines)==192, (len(lines),result.stdout[:500])
    with tempfile.TemporaryDirectory() as folder:
        p=pathlib.Path(folder)
        for i,(_,dtype,values,encoding,endian,detached) in enumerate(vectors()):
            head=bytes(json.loads(lines[2*i])); payload=bytes(json.loads(lines[2*i+1]))
            f=p/('out.nhdr' if detached else 'out.nrrd')
            if detached:
                f.write_bytes(head); (p/'payload.raw').write_bytes(payload)
            else: f.write_bytes(head+payload)
            if encoding=='hex':
                head=head.replace(b'encoding: hex',b'encoding: raw'); payload=bytes.fromhex(payload.decode('ascii'))
                if detached: f.write_bytes(head); (p/'payload.raw').write_bytes(payload)
                else: f.write_bytes(head+payload)
            actual,header=nrrd.read(str(f),index_order='F')
            expected=np.array(values,dtype=dtype).reshape((2,2),order='F')
            np.testing.assert_array_equal(actual,expected)
            assert list(header['labels'])==['x','time']
            assert header['source']=='MoonNRRD'
    print('Independent oracle passed in each direction: 64 direct pynrrd raw/ASCII vectors + 32 hex vectors via independent Python hex/raw bridge. ASCII endian permutations are equivalent textual cases.')
if __name__=='__main__': main()

